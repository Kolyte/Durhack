import { audioEngine, engineStore } from '../audio/AudioEngine';
import { describeFile } from '../audio/composer';
import { PRESETS } from '../audio/presets';
import { useEffect, useState } from 'react';
import { explainFile, type FileExplanation } from '../model/explain';
import type { FileInfo, RepoModel } from '../model/repoModel';
import { accountStore, loadMe, openPricing } from '../state/account';
import { cachedExplanation, explainWithGemini, GeminiError, geminiStatus, type GeminiExplanation } from '../state/gemini';
import { useStore } from '../state/store';
import type { RepoMeta } from '../types';

const ROLE_LABEL: Record<FileInfo['kind'], string> = {
  source: 'Source file',
  module: 'Module / entry point',
  test: 'Test',
  config: 'Configuration',
  docs: 'Documentation',
};

/**
 * "What it's for": the built-in explanation straight away, plus an optional Gemini explanation
 * (on request, to save the free quota). Keyed by file in the parent, so state resets per file.
 */
function WhatItsFor({ file, model, meta }: { file: FileInfo; model: RepoModel; meta: RepoMeta | null }) {
  const builtIn = explainFile(file, model);
  const [enabled, setEnabled] = useState(false);
  const [gemini, setGemini] = useState<GeminiExplanation | null>(() => (meta ? (cachedExplanation(meta, file) ?? null) : null));
  const [state, setState] = useState<'idle' | 'loading' | 'error'>('idle');
  const [error, setError] = useState('');
  const { me } = useStore(accountStore);

  useEffect(() => {
    let alive = true;
    void geminiStatus().then((s) => alive && setEnabled(s.enabled));
    return () => {
      alive = false;
    };
  }, []);

  const ask = async () => {
    if (!meta) return;
    if (!me.canUsePro) return openPricing();
    setState('loading');
    try {
      setGemini(await explainWithGemini(meta, file));
      setState('idle');
    } catch (e) {
      if (e instanceof GeminiError && (e.code === 'sign_in' || e.code === 'pro_required')) {
        // The session expired or the subscription lapsed: refresh the account and show the plans.
        setState('idle');
        void loadMe();
        return openPricing();
      }
      setError(e instanceof Error ? e.message : 'Gemini request failed');
      setState('error');
    }
  };

  const shown: FileExplanation = gemini ?? builtIn;
  return (
    <>
      <h3 className="panel__title">
        What it's for
        {gemini && <span className="ai-badge">✨ Gemini</span>}
      </h3>
      <p className="about">{shown.purpose}</p>
      {shown.details.length > 0 && (
        <ul className="explain">
          {shown.details.map((d) => (
            <li key={d}>{d}</li>
          ))}
        </ul>
      )}
      {enabled && !gemini && meta && (
        <button className="btn btn--ghost btn--block btn--ai" onClick={ask} disabled={state === 'loading'}>
          {state === 'loading' ? 'Asking Gemini…' : '✨ Explain with Gemini'}
          {!me.canUsePro && <span className="plan-badge plan-badge--pro">Pro</span>}
        </button>
      )}
      {state === 'error' && <p className="note note--error">{error} Showing the built-in explanation.</p>}
      {gemini && <p className="note">Generated by {gemini.model}. AI can make mistakes.</p>}
    </>
  );
}

export function FileInspector({
  file,
  model,
  meta,
  onSelect,
  onClose,
}: {
  file: FileInfo;
  model: RepoModel;
  meta: RepoMeta | null;
  onSelect: (id: string) => void;
  onClose: () => void;
}) {
  const { preset, variant, rotation } = useStore(engineStore);
  const group = model.groupIndex.get(file.group);
  const name = file.path.split('/').pop();
  const links = [
    ...file.deps.map((id) => ({ id, dir: 'imports' as const })),
    ...file.dependents.map((id) => ({ id, dir: 'imported by' as const })),
  ];

  return (
    <aside className="inspector panel" aria-label="File inspector">
      <div className="panel__head">
        <div>
          <div className="eyebrow">{ROLE_LABEL[file.kind]}</div>
          <h2 className="inspector__name">{name}</h2>
          <div className="inspector__path">{file.path}</div>
        </div>
        <button className="btn btn--icon" onClick={onClose} aria-label="Close inspector">
          ✕
        </button>
      </div>

      <dl className="stats">
        <div>
          <dt>Lines</dt>
          <dd>{file.analyzed ? file.loc : `~${file.loc}`}</dd>
        </div>
        <div>
          <dt>Complexity</dt>
          <dd>{file.role === 'source' || file.role === 'test' ? file.complexity : '—'}</dd>
        </div>
        <div>
          <dt>Imports</dt>
          <dd>{file.imports}</dd>
        </div>
        <div>
          <dt>Concurrency</dt>
          <dd>{file.concurrency}</dd>
        </div>
        <div className="stats__wide">
          <dt>Directory</dt>
          <dd>{group?.label ?? '—'}</dd>
        </div>
      </dl>

      <WhatItsFor key={file.id} file={file} model={model} meta={meta} />

      <button className="btn btn--primary btn--block" onClick={() => audioEngine.playSignature(file)}>
        ♪ Play musical signature
      </button>

      <h3 className="panel__title">How it shapes the music</h3>
      <ul className="explain">
        {describeFile(file, PRESETS[preset], (group?.index ?? 0) + rotation, variant).map((l) => (
          <li key={l}>{l}</li>
        ))}
      </ul>

      {links.length > 0 && (
        <>
          <h3 className="panel__title">Connections ({links.length})</h3>
          <ul className="links">
            {links.map((l) => (
              <li key={`${l.dir}-${l.id}`}>
                <button className="link" onClick={() => onSelect(l.id)}>
                  <span className="links__dir">{l.dir}</span> {l.id.split('/').pop()}
                </button>
              </li>
            ))}
          </ul>
        </>
      )}
      {!file.analyzed && <p className="note">Not fetched yet; size is estimated from the file's byte count.</p>}
    </aside>
  );
}
